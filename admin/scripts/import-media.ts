// One-shot: read ../media/media.json and emit migrations/seeds/0001_seed.sql.
// Run with: pnpm tsx scripts/import-media.ts [path-to-media.json]
// Then: wrangler d1 execute gallery-admin --local --file=migrations/seeds/0001_seed.sql
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type MediaCamera = { make: string; model: string };
type MediaInfoJSON = {
  file: string;
  world: "Real" | "VRChat";
  timestamp: string | null;
  camera: MediaCamera | null;
  tags: string[];
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const adminRoot = resolve(__dirname, "..");
const repoRoot = resolve(adminRoot, "..");

const inputPath = process.argv[2]
  ? resolve(process.cwd(), process.argv[2])
  : resolve(repoRoot, "media", "media.json");

const outPath = resolve(adminRoot, "migrations", "seeds", "0001_seed.sql");

// SQLite's string-literal grammar only treats `'` as special, so doubling it
// is sufficient. Reject any control character or `;` — the latter doesn't
// confuse SQLite's parser inside a literal but wrangler's CLI splits .sql
// input on it, and the former would silently break the seed file.
const REJECT_CHARS = /[\x00-\x1f;]/;
const escape = (s: string) => {
  if (REJECT_CHARS.test(s)) {
    throw new Error(
      `unsupported character in field: ${JSON.stringify(s)} ` +
        `(rejected: control chars or ';' — wrangler d1 execute --file ` +
        `splits the SQL on ';' and a stray control char would break the seed)`,
    );
  }
  return s.replace(/'/g, "''");
};
const sqlString = (v: string | null | undefined) =>
  v == null ? "NULL" : `'${escape(v)}'`;

const json = readFileSync(inputPath, "utf8");
const items = JSON.parse(json) as MediaInfoJSON[];
if (!Array.isArray(items)) {
  throw new Error(`expected array at ${inputPath}, got ${typeof items}`);
}

const lines: string[] = [
  "-- Auto-generated by scripts/import-media.ts. Do not edit by hand.",
  `-- Source: ${inputPath}`,
  `-- Rows: ${items.length}`,
  "BEGIN TRANSACTION;",
];

for (const item of items) {
  if (item.world !== "Real" && item.world !== "VRChat") {
    throw new Error(`invalid world for ${item.file}: ${item.world}`);
  }
  const cols = [
    sqlString(item.file),
    sqlString(item.world),
    sqlString(item.timestamp),
    sqlString(item.camera?.make ?? null),
    sqlString(item.camera?.model ?? null),
    sqlString(JSON.stringify(item.tags ?? [])),
  ].join(", ");
  lines.push(
    `INSERT OR IGNORE INTO media (file, world, timestamp, camera_make, camera_model, tags) VALUES (${cols});`,
  );
}

lines.push("COMMIT;", "");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join("\n"), "utf8");

console.log(`wrote ${items.length} rows to ${outPath}`);
