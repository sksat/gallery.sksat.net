// One-shot: read ../media/media.json and emit migrations/seeds/0001_seed.sql.
// Run with: pnpm tsx scripts/import-media.ts [path-to-media.json]
// Then: wrangler d1 execute gallery-admin --local --file=migrations/seeds/0001_seed.sql
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type MediaCamera = { make: string; model: string };
type MediaInfoJSON = {
  file: string;
  world: "Real" | "VRChat";
  timestamp: string | null;
  camera: MediaCamera | null;
  tags: string[];
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const adminRoot = resolve(__dirname, "..");
const repoRoot = resolve(adminRoot, "..");

const inputPath = process.argv[2]
  ? resolve(process.cwd(), process.argv[2])
  : resolve(repoRoot, "media", "media.json");

const outPath = resolve(adminRoot, "migrations", "seeds", "0001_seed.sql");

// SQLite's string-literal grammar only treats `'` as special, so doubling it
// is sufficient. Reject any control character or `;` — the latter doesn't
// confuse SQLite's parser inside a literal but wrangler's CLI splits .sql
// input on it, and the former would silently break the seed file.
const REJECT_CHARS = /[\x00-\x1f;]/;
const escape = (s: string) => {
  if (REJECT_CHARS.test(s)) {
    throw new Error(
      `unsupported character in field: ${JSON.stringify(s)} ` +
        `(rejected: control chars or ';' — wrangler d1 execute --file ` +
        `splits the SQL on ';' and a stray control char would break the seed)`,
    );
  }
  return s.replace(/'/g, "''");
};
const sqlString = (v: string | null | undefined) =>
  v == null ? "NULL" : `'${escape(v)}'`;

const json = readFileSync(inputPath, "utf8");
const items = JSON.parse(json) as MediaInfoJSON[];
if (!Array.isArray(items)) {
  throw new Error(`expected array at ${inputPath}, got ${typeof items}`);
}

const lines: string[] = [
  "-- Auto-generated by scripts/import-media.ts. Do not edit by hand.",
  `-- Source: ${inputPath}`,
  `-- Rows: ${items.length}`,
  // No explicit BEGIN TRANSACTION / COMMIT — `wrangler d1 execute --remote`
  // rejects them ("use storage.transaction()" error). Wrangler wraps the
  // file's statements appropriately for both --local and --remote.
];

const mediaLines: string[] = [];
const cameras = new Map<
  string,
  { make: string; model: string; onlyVRChat: boolean }
>();

for (const item of items) {
  if (typeof item.file !== "string" || item.file === "") {
    throw new Error(
      `invalid 'file' field (expected non-empty string): ${JSON.stringify(item)}`,
    );
  }
  if (item.world !== "Real" && item.world !== "VRChat") {
    throw new Error(`invalid world for ${item.file}: ${item.world}`);
  }
  // Note: this script does not structurally validate `timestamp`,
  // `camera_make`, or `camera_model`. They flow into D1 verbatim — the
  // public gallery's date parser will fall back to displaying the raw
  // string for non-ISO timestamps. Acceptable for a one-shot importer
  // staring at a known-good media.json.
  // tags: must be string[] — non-string entries would survive into D1 and
  // later trip parseTags() at read time. Catch it here, where the source
  // file is still in front of the operator.
  if (item.tags != null) {
    if (!Array.isArray(item.tags)) {
      throw new Error(
        `tags must be an array for ${item.file}: ${JSON.stringify(item.tags)}`,
      );
    }
    if (!item.tags.every((t) => typeof t === "string")) {
      throw new Error(
        `tags must be an array of strings for ${item.file}: ${JSON.stringify(item.tags)}`,
      );
    }
  }
  // A camera is identified by its make + model pair (one cameras row each).
  if (item.camera != null) {
    if (
      typeof item.camera.make !== "string" ||
      typeof item.camera.model !== "string"
    ) {
      throw new Error(
        `camera must be { make, model } as a pair for ${item.file}: ${JSON.stringify(item.camera)}`,
      );
    }
  }
  let cameraId = "NULL";
  if (item.camera != null) {
    const { make, model } = item.camera;
    const key = JSON.stringify([make, model]);
    if (!cameras.has(key)) {
      cameras.set(key, { make, model, onlyVRChat: true });
    }
    if (item.world !== "VRChat") cameras.get(key)!.onlyVRChat = false;
    cameraId = `(SELECT id FROM cameras WHERE make = ${sqlString(make)} AND model = ${sqlString(model)})`;
  }
  const cols = [
    sqlString(item.file),
    sqlString(item.world),
    sqlString(item.timestamp),
    cameraId,
    sqlString(JSON.stringify(item.tags ?? [])),
  ].join(", ");
  mediaLines.push(
    `INSERT OR IGNORE INTO media (file, world, timestamp, camera_id, tags) VALUES (${cols});`,
  );
}

// Cameras go first so the media rows' camera_id subqueries resolve. Same
// naming rule as the backfill in migrations/0002_cameras.sql. A camera that
// already exists (same make + model) is reused; INSERT OR IGNORE also skips
// one whose slug is taken, in which case its photos are imported without a
// camera — fix them up in the admin.
const cmp = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const usedSlugs = new Set<string>();
const sortedCameras = [...cameras.values()].sort(
  (a, b) => cmp(a.make, b.make) || cmp(a.model, b.model),
);
for (const { make, model, onlyVRChat } of sortedCameras) {
  let base = model
    .trim()
    .toLowerCase()
    .replace(/[ /_.]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  if (base === "" || /[^a-z0-9-]/.test(base)) base = "camera";
  let slug = base;
  for (let n = 2; usedSlugs.has(slug); n++) slug = `${base}-${n}`;
  usedSlugs.add(slug);
  lines.push(
    `INSERT OR IGNORE INTO cameras (slug, name, make, model, kind) ` +
      `SELECT ${sqlString(slug)}, ${sqlString(`${make} ${model}`)}, ${sqlString(make)}, ${sqlString(model)}, ${onlyVRChat ? "'virtual'" : "NULL"} ` +
      `WHERE NOT EXISTS (SELECT 1 FROM cameras WHERE make = ${sqlString(make)} AND model = ${sqlString(model)});`,
  );
}
lines.push(...mediaLines);

lines.push("");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join("\n"), "utf8");

console.log(`wrote ${items.length} rows to ${outPath}`);
