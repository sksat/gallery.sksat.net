// Generates src/lib/world-map.gen.ts, the world map of /analytics/: one
// SVG path per country of Natural Earth's 1:110m countries (world-atlas),
// in the Equal Earth projection (equal area, so a country's shade is not
// exaggerated by its size), keyed by its ISO 3166-1 alpha-2 code, the
// code Web Analytics reports. Antarctica is left out. Run again after
// updating world-atlas:
//
//   pnpm exec tsx scripts/gen-world-map.ts
//
// The map is drawn on the server, so the page needs neither the atlas nor
// a projection library at runtime.

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEqualEarth, geoPath } from "d3-geo";
import countries from "i18n-iso-countries";
import { feature } from "topojson-client";
import type { Topology, GeometryCollection } from "topojson-specification";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-110m.json") as Topology<{
  countries: GeometryCollection<{ name: string }>;
}>;

const WIDTH = 960;
// Natural Earth features with no ISO numeric id.
const NO_ID: Record<string, string> = { Kosovo: "XK" };

const fc = feature(topo, topo.objects.countries);
const shown = fc.features.filter((f) => f.id !== "010"); // Antarctica
const projection = geoEqualEarth().fitWidth(WIDTH, {
  type: "FeatureCollection",
  features: shown,
});
const path = geoPath(projection).digits(0);
const [[, y0], [, y1]] = path.bounds({
  type: "FeatureCollection",
  features: shown,
});
const height = Math.ceil(y1 - Math.min(0, y0));

/**
 * d3's absolute "M1,2L3,4Z" as relative moves and lines ("m1 2l2 2z"),
 * which with whole pixels is about a third shorter. Repeated points are
 * dropped.
 */
const relative = (d: string): string => {
  let out = "";
  let x = 0;
  let y = 0;
  // After "z" the current point is back at the subpath's start.
  let sx = 0;
  let sy = 0;
  for (const [, cmd, args] of d.matchAll(/([MLZ])([^MLZ]*)/g)) {
    if (cmd === "Z") {
      out += "z";
      x = sx;
      y = sy;
      continue;
    }
    const nums = args.split(/[ ,]/).filter(Boolean).map(Number);
    for (let i = 0; i < nums.length; i += 2) {
      const dx = nums[i] - x;
      const dy = nums[i + 1] - y;
      x = nums[i];
      y = nums[i + 1];
      if (cmd === "M") {
        sx = x;
        sy = y;
      } else if (dx === 0 && dy === 0) continue;
      const pair = `${dx}${dy < 0 ? "" : " "}${dy}`;
      out += cmd === "M" ? `m${pair}` : `l${pair}`;
    }
  }
  return out;
};

const rows = shown
  .map((f) => {
    const name = f.properties?.name ?? "";
    const code =
      f.id === undefined
        ? (NO_ID[name] ?? null)
        : (countries.numericToAlpha2(String(f.id)) ?? null);
    return { code, name, d: relative(path(f) ?? "") };
  })
  .filter((r) => r.d !== "")
  .sort((a, b) => (a.code ?? a.name).localeCompare(b.code ?? b.name));

const out = `// Generated by scripts/gen-world-map.ts from world-atlas countries-110m
// (Natural Earth, public domain). Do not edit.

export const WORLD_WIDTH = ${WIDTH};
export const WORLD_HEIGHT = ${height};

/** One path per country: its ISO 3166-1 alpha-2 code (null for a few
 * Natural Earth areas without one) and its English name. */
export const WORLD_COUNTRIES: readonly {
  code: string | null;
  name: string;
  d: string;
}[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL("../src/lib/world-map.gen.ts", import.meta.url), out);
console.log(`${rows.length} countries, ${out.length} bytes`);
