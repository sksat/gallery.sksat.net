// Generates src/lib/referrer-icons.gen.ts: the brand icons of the
// well-known referrers (src/lib/referrer-icon.ts says which hosts are
// which), from Simple Icons (CC0). Bundled so a referrer list shows them
// without any request. Run again after updating simple-icons or the list:
//
//   pnpm exec tsx scripts/gen-referrer-icons.ts
//
// Simple Icons has no Bing, Yahoo or Slack icon (their owners asked for
// removal); those come from the favicon route like any other site.

import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

type SimpleIcon = { title: string; hex: string; path: string };

// Our key → Simple Icons export.
const ICONS: Record<string, SimpleIcon> = {
  x: si.siX,
  google: si.siGoogle,
  duckduckgo: si.siDuckduckgo,
  discord: si.siDiscord,
  github: si.siGithub,
  bluesky: si.siBluesky,
  // Mastodon, Misskey and the rest of the fediverse share one icon.
  fediverse: si.siActivitypub,
  facebook: si.siFacebook,
  instagram: si.siInstagram,
  youtube: si.siYoutube,
  reddit: si.siReddit,
  hatena: si.siHatenabookmark,
  line: si.siLine,
  threads: si.siThreads,
  pixiv: si.siPixiv,
  note: si.siNote,
  qiita: si.siQiita,
  zenn: si.siZenn,
};

/** Relative luminance of "rrggbb" (WCAG). */
const luminance = (hex: string): number => {
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const rows = Object.fromEntries(
  Object.entries(ICONS).map(([key, icon]) => [
    key,
    {
      title: icon.title,
      // Near-black marks (X, GitHub, …) take the text colour instead, so
      // they show on the dark theme too.
      color: luminance(icon.hex) < 0.05 ? null : `#${icon.hex}`,
      path: icon.path,
    },
  ]),
);

const out = `// Generated by scripts/gen-referrer-icons.ts from simple-icons (CC0).
// Do not edit.

export type BrandIcon = {
  title: string;
  /** The brand colour, or null to use the text colour. */
  color: string | null;
  /** One SVG path in a 24×24 box. */
  path: string;
};

export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(
  new URL("../src/lib/referrer-icons.gen.ts", import.meta.url),
  out,
);
console.log(`${Object.keys(rows).length} icons, ${out.length} bytes`);
